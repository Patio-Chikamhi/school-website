// src/components/shared/ReportViewer.jsx - MOBILE OPTIMIZED
import React, { useState } from 'react';
import { Download, Printer, ChevronDown, ChevronUp, Eye, XCircle } from 'lucide-react';

const getGradeColorClass = (letterGrade) => {
  const colors = {
    'A': 'text-emerald-600',
    'B': 'text-blue-600',
    'C': 'text-yellow-600',
    'D': 'text-orange-600',
    'F': 'text-red-600'
  };
  return colors[letterGrade] || 'text-gray-600';
};

export const ReportViewer = ({ report, onClose, userType = 'parent' }) => {
  const [expandedSubject, setExpandedSubject] = useState(null);
  const [showAuditTrail, setShowAuditTrail] = useState(false);

  const isSingleSubject = report.reportType === 'single-subject' || (!report.subjects && report.courseName);

  const toggleSubject = (subjectId) => {
    setExpandedSubject(expandedSubject === subjectId ? null : subjectId);
  };

  const downloadReport = () => {
    const printWindow = window.open('', '_blank');
    printWindow.document.write(getReportHTML());
    printWindow.document.close();
    printWindow.print();
  };

  const getReportHTML = () => {
    const fmt = (n) => (typeof n === 'number' ? n.toFixed(1) : '0.0');

    if (isSingleSubject) {
      return `
        <!DOCTYPE html>
        <html>
        <head>
          <title>${report.studentName} - ${report.courseName} Report</title>
          <style>
            body { font-family: Arial, sans-serif; margin: 40px; }
            .header { text-align: center; margin-bottom: 30px; }
            .school-name { font-size: 28px; font-weight: bold; color: #1e40af; }
            .report-title { font-size: 20px; margin-top: 10px; }
            .student-info { background: #f3f4f6; padding: 15px; border-radius: 8px; margin-bottom: 20px; }
            .summary-cards { display: grid; grid-template-columns: repeat(3, 1fr); gap: 15px; margin-bottom: 30px; }
            .card { background: linear-gradient(135deg, #667eea 0%, #764ba2 100%); color: white; padding: 15px; border-radius: 10px; text-align: center; }
            .grade-table { width: 100%; border-collapse: collapse; margin-top: 20px; }
            .grade-table th, .grade-table td { padding: 10px; text-align: left; border-bottom: 1px solid #e5e7eb; }
            .grade-table th { background: #f9fafb; }
            .footer { margin-top: 30px; text-align: center; font-size: 12px; color: #6b7280; }
          </style>
        </head>
        <body>
          <div class="header">
            <div class="school-name">Evergreen Academy</div>
            <div class="report-title">${report.courseName} Report - ${report.term} ${report.academicYearString || report.academicYear}</div>
          </div>
          <div class="student-info">
            <p><strong>Student:</strong> ${report.studentName}</p>
            <p><strong>Student ID:</strong> ${report.studentId}</p>
            <p><strong>Course:</strong> ${report.courseName}</p>
            <p><strong>Teacher:</strong> ${report.teacherName}</p>
          </div>
          <div class="summary-cards">
            <div class="card"><strong>Overall Average</strong><br>${fmt(report.summary?.average || report.overallAverage)}%<br>Grade ${report.summary?.letterGrade || report.overallGrade}</div>
            <div class="card"><strong>Assignments</strong><br>${report.summary?.totalAssignments || report.grades?.length || 0}</div>
            <div class="card"><strong>Highest Score</strong><br>${fmt(report.summary?.highestScore)}%</div>
          </div>
          <h3>Assignment Grades</h3>
          <table class="grade-table">
            <thead>
              <tr><th>Assignment</th><th>Type</th><th>Score</th><th>Percentage</th><th>Grade</th></tr>
            </thead>
            <tbody>
              ${report.grades?.map(g => `
                <tr>
                  <td>${g.assignmentName}</td>
                  <td>${g.assignmentType}</td>
                  <td>${g.score}/${g.maxScore}</td>
                  <td>${fmt(g.percentage)}%</td>
                  <td>${g.letterGrade}</td>
                </tr>
              `).join('')}
            </tbody>
          </table>
          ${report.teacherComments ? `<div style="margin-top: 20px; padding: 15px; background: #fef3c7; border-radius: 8px;"><strong>Teacher Comments:</strong><p>${report.teacherComments}</p></div>` : ''}
          <div class="footer">
            <p>Generated on: ${new Date().toLocaleDateString()}</p>
            <p>Generated by: ${report.generatedBy || 'System'}</p>
          </div>
        </body>
        </html>
      `;
    }

    return `
      <!DOCTYPE html>
      <html>
      <head>
        <title>${report.studentName} - ${report.term} Report</title>
        <style>
          body { font-family: Arial, sans-serif; margin: 40px; }
          .header { text-align: center; margin-bottom: 30px; }
          .school-name { font-size: 28px; font-weight: bold; color: #1e40af; }
          .report-title { font-size: 20px; margin-top: 10px; }
          .student-info { background: #f3f4f6; padding: 15px; border-radius: 8px; margin-bottom: 20px; }
          .summary-cards { display: grid; grid-template-columns: repeat(3, 1fr); gap: 15px; margin-bottom: 30px; }
          .card { background: linear-gradient(135deg, #667eea 0%, #764ba2 100%); color: white; padding: 15px; border-radius: 10px; text-align: center; }
          .subject { border: 1px solid #e5e7eb; border-radius: 8px; margin-bottom: 20px; overflow: hidden; }
          .subject-header { background: #f9fafb; padding: 15px; border-bottom: 1px solid #e5e7eb; }
          .assessment-table { width: 100%; border-collapse: collapse; }
          .assessment-table th, .assessment-table td { padding: 10px; text-align: left; border-bottom: 1px solid #e5e7eb; }
          .grade-A { color: #10b981; font-weight: bold; }
          .grade-B { color: #3b82f6; font-weight: bold; }
          .grade-C { color: #f59e0b; font-weight: bold; }
          .grade-D { color: #ef4444; font-weight: bold; }
          .grade-F { color: #ef4444; font-weight: bold; }
          .footer { margin-top: 30px; text-align: center; font-size: 12px; color: #6b7280; }
          @media print { body { margin: 0; padding: 20px; } }
        </style>
      </head>
      <body>
        <div class="header">
          <div class="school-name">Evergreen Academy</div>
          <div class="report-title">${report.term} Academic Report - ${report.academicYearString || report.academicYear}</div>
        </div>
        <div class="student-info">
          <p><strong>Student Name:</strong> ${report.studentName}</p>
          <p><strong>Student ID:</strong> ${report.studentId}</p>
          <p><strong>Form:</strong> ${report.grade || report.studentGrade || 'N/A'}</p>
        </div>
        <div class="summary-cards">
          <div class="card"><strong>Overall Average</strong><br>${fmt(report.overallAverage)}%<br>Grade ${report.overallGrade}</div>
          <div class="card"><strong>Attendance Rate</strong><br>${fmt(report.attendanceRate)}%</div>
          <div class="card"><strong>Subjects Taken</strong><br>${report.subjects?.length || 0}</div>
        </div>
        ${report.subjects?.map(subject => `
          <div class="subject">
            <div class="subject-header">
              <strong>${subject.courseName}</strong> - Teacher: ${subject.teacherName}<br>
              Final Grade: <span class="grade-${subject.letterGrade}">${fmt(subject.average)}% (${subject.letterGrade})</span>
            </div>
            <table class="assessment-table">
              <thead><tr><th>Assessment</th><th>Type</th><th>Score</th><th>Max Score</th><th>Percentage</th><th>Date</th></tr></thead>
              <tbody>
                ${subject.grades?.map(g => `
                  <tr>
                    <td>${g.name}</td>
                    <td>${g.type}</td>
                    <td>${g.score}</td>
                    <td>${g.maxScore}</td>
                    <td>${fmt((g.score / g.maxScore) * 100)}%</td>
                    <td>${new Date(g.date).toLocaleDateString()}</td>
                  </tr>
                `).join('')}
              </tbody>
            </table>
          </div>
        `).join('')}
        ${report.teacherComments ? `<div style="margin-top: 20px; padding: 15px; background: #fef3c7; border-radius: 8px;"><strong>Teacher Comments:</strong><p>${report.teacherComments}</p></div>` : ''}
        <div class="footer">
          <p>Generated on: ${new Date().toLocaleDateString()}</p>
          <p>Generated by: ${report.generatedBy || 'System'}</p>
          <p>This is an official report of Evergreen Academy</p>
        </div>
      </body>
      </html>
    `;
  };

  // ==========================================
  // SINGLE SUBJECT VIEW
  // ==========================================
  if (isSingleSubject) {
    const summary = report.summary || {};
    const average = summary.average || report.overallAverage || 0;
    const letterGrade = summary.letterGrade || report.overallGrade || 'F';

    return (
      <div className="fixed inset-0 bg-black/50 flex items-center justify-center z-50 p-4 pb-24 lg:pb-4">
        <div className="bg-white rounded-xl w-full max-w-4xl max-h-[calc(100vh-140px)] lg:max-h-[90vh] flex flex-col">
          {/* Header */}
          <div className="bg-white border-b border-gray-200 px-4 sm:px-6 py-3 sm:py-4 flex items-center justify-between flex-shrink-0 gap-2">
            <div className="min-w-0">
              <h2 className="text-base sm:text-xl font-bold text-gray-900 truncate">Single Subject Report</h2>
              <p className="text-xs sm:text-sm text-gray-500 truncate">
                {report.studentName} • {report.courseName}
              </p>
            </div>
            <div className="flex gap-1 sm:gap-2 flex-shrink-0">
              <button
                onClick={downloadReport}
                className="p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg"
                title="Download"
              >
                <Download className="w-4 h-4 sm:w-5 sm:h-5 text-gray-600" />
              </button>
              <button
                onClick={() => window.print()}
                className="p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg"
                title="Print"
              >
                <Printer className="w-4 h-4 sm:w-5 sm:h-5 text-gray-600" />
              </button>
              <button
                onClick={onClose}
                className="p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg"
              >
                <XCircle className="w-5 h-5 sm:w-6 sm:h-6 text-gray-400" />
              </button>
            </div>
          </div>

          <div className="p-4 sm:p-6 overflow-y-auto flex-1">
            {/* School Header */}
            <div className="text-center mb-6 sm:mb-8">
              <h1 className="text-2xl sm:text-3xl font-bold text-gray-900">Evergreen Academy</h1>
              <p className="text-gray-600 text-sm sm:text-base">Excellence in Education</p>
              <div className="border-b-2 border-gray-300 mt-3 sm:mt-4"></div>
              <h2 className="text-xl sm:text-2xl font-semibold mt-3 sm:mt-4">{report.courseName} Report</h2>
              <p className="text-gray-600 text-sm sm:text-base">
                {report.term} {report.academicYearString || report.academicYear}
              </p>
            </div>

            {/* Student Info */}
            <div className="bg-gray-50 p-3 sm:p-4 rounded-lg mb-6">
              <div className="grid grid-cols-2 md:grid-cols-4 gap-3 sm:gap-4">
                <div>
                  <p className="text-xs sm:text-sm text-gray-500">Student</p>
                  <p className="font-semibold text-sm sm:text-base truncate">{report.studentName}</p>
                </div>
                <div>
                  <p className="text-xs sm:text-sm text-gray-500">Student ID</p>
                  <p className="font-semibold text-sm sm:text-base truncate">{report.studentId}</p>
                </div>
                <div>
                  <p className="text-xs sm:text-sm text-gray-500">Teacher</p>
                  <p className="font-semibold text-sm sm:text-base truncate">{report.teacherName}</p>
                </div>
                <div>
                  <p className="text-xs sm:text-sm text-gray-500">Course</p>
                  <p className="font-semibold text-sm sm:text-base truncate">{report.courseName}</p>
                </div>
              </div>
            </div>

            {/* Summary Cards */}
            <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 sm:gap-4 mb-6 sm:mb-8">
              <div className="bg-gradient-to-r from-emerald-500 to-emerald-600 rounded-lg p-3 sm:p-4 text-white text-center">
                <div className="text-2xl sm:text-3xl font-bold">{average.toFixed(1)}%</div>
                <div className="text-xs sm:text-sm">Overall Average</div>
                <div className="text-lg sm:text-xl mt-2">Grade {letterGrade}</div>
              </div>
              <div className="bg-gradient-to-r from-blue-500 to-blue-600 rounded-lg p-3 sm:p-4 text-white text-center">
                <div className="text-2xl sm:text-3xl font-bold">
                  {summary.totalAssignments || report.grades?.length || 0}
                </div>
                <div className="text-xs sm:text-sm">Total Assignments</div>
              </div>
              <div className="bg-gradient-to-r from-purple-500 to-purple-600 rounded-lg p-3 sm:p-4 text-white text-center">
                <div className="text-2xl sm:text-3xl font-bold">
                  {(summary.highestScore || 0).toFixed(1)}%
                </div>
                <div className="text-xs sm:text-sm">Highest Score</div>
              </div>
            </div>

            {/* Assignment Grades Table — Mobile scrollable */}
            <h3 className="text-lg sm:text-xl font-bold mb-3 sm:mb-4">Assignment Grades</h3>
            <div className="overflow-x-auto -mx-4 sm:-mx-6 px-4 sm:px-6">
              <table className="w-full text-sm min-w-[560px]">
                <thead className="bg-gray-100">
                  <tr>
                    <th className="py-2 px-3 text-left">Assignment</th>
                    <th className="py-2 px-3 text-center">Type</th>
                    <th className="py-2 px-3 text-center">Score</th>
                    <th className="py-2 px-3 text-center">%</th>
                    <th className="py-2 px-3 text-center">Grade</th>
                    <th className="py-2 px-3 text-left">Comments</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100">
                  {report.grades?.map((g, idx) => (
                    <tr key={idx} className="hover:bg-gray-50">
                      <td className="py-2 px-3">{g.assignmentName}</td>
                      <td className="py-2 px-3 text-center capitalize">{g.assignmentType}</td>
                      <td className="py-2 px-3 text-center">{g.score}/{g.maxScore}</td>
                      <td className="py-2 px-3 text-center">{g.percentage?.toFixed(1)}%</td>
                      <td className={`py-2 px-3 text-center font-bold ${getGradeColorClass(g.letterGrade)}`}>
                        {g.letterGrade}
                      </td>
                      <td className="py-2 px-3 text-gray-600 text-xs">
                        {g.comments || '-'}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>

            {/* Teacher Comments */}
            <div className="mt-6 sm:mt-8">
              <h3 className="text-lg sm:text-xl font-bold mb-2">Teacher's Comments</h3>
              <div className="bg-gray-50 p-3 sm:p-4 rounded-lg">
                <p className="text-sm sm:text-base text-gray-700">
                  {report.teacherComments || 'No comments provided.'}
                </p>
              </div>
            </div>
          </div>
        </div>
      </div>
    );
  }

  // ==========================================
  // TERM REPORT VIEW
  // ==========================================
  return (
    <div className="fixed inset-0 bg-black/50 flex items-center justify-center z-50 p-4 pb-24 lg:pb-4">
      <div className="bg-white rounded-xl w-full max-w-4xl max-h-[calc(100vh-140px)] lg:max-h-[90vh] flex flex-col">
        {/* Header */}
        <div className="bg-white border-b border-gray-200 px-4 sm:px-6 py-3 sm:py-4 flex items-center justify-between flex-shrink-0 gap-2">
          <div className="min-w-0">
            <h2 className="text-base sm:text-xl font-bold text-gray-900 truncate">Term Report</h2>
            <p className="text-xs sm:text-sm text-gray-500 truncate">
              {report.studentName} • {report.term} {report.academicYearString || report.academicYear}
            </p>
          </div>
          <div className="flex gap-1 sm:gap-2 flex-shrink-0">
            <button
              onClick={downloadReport}
              className="p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg"
              title="Download"
            >
              <Download className="w-4 h-4 sm:w-5 sm:h-5 text-gray-600" />
            </button>
            <button
              onClick={() => window.print()}
              className="p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg"
              title="Print"
            >
              <Printer className="w-4 h-4 sm:w-5 sm:h-5 text-gray-600" />
            </button>
            {userType === 'admin' && (
              <button
                onClick={() => setShowAuditTrail(!showAuditTrail)}
                className={`p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg ${
                  showAuditTrail ? 'bg-emerald-100 text-emerald-600' : ''
                }`}
                title="Audit Trail"
              >
                <Eye className="w-4 h-4 sm:w-5 sm:h-5" />
              </button>
            )}
            <button
              onClick={onClose}
              className="p-1.5 sm:p-2 hover:bg-gray-100 rounded-lg"
            >
              <XCircle className="w-5 h-5 sm:w-6 sm:h-6 text-gray-400" />
            </button>
          </div>
        </div>

        <div className="p-4 sm:p-6 overflow-y-auto flex-1">
          {/* School Header */}
          <div className="text-center mb-6 sm:mb-8">
            <h1 className="text-2xl sm:text-3xl font-bold text-gray-900">Evergreen Academy</h1>
            <p className="text-gray-600 text-sm sm:text-base">Excellence in Education</p>
            <div className="border-b-2 border-gray-300 mt-3 sm:mt-4"></div>
            <h2 className="text-xl sm:text-2xl font-semibold mt-3 sm:mt-4">
              {report.term} Academic Report
            </h2>
            <p className="text-gray-600 text-sm sm:text-base">
              Academic Year {report.academicYearString || report.academicYear}
            </p>
          </div>

          {/* Student Info */}
          <div className="bg-gray-50 p-3 sm:p-4 rounded-lg mb-6">
            <div className="grid grid-cols-2 md:grid-cols-5 gap-3 sm:gap-4">
              <div>
                <p className="text-xs sm:text-sm text-gray-500">Student Name</p>
                <p className="font-semibold text-sm sm:text-base truncate">{report.studentName}</p>
              </div>
              <div>
                <p className="text-xs sm:text-sm text-gray-500">Student ID</p>
                <p className="font-semibold text-sm sm:text-base truncate">{report.studentId}</p>
              </div>
              <div>
                <p className="text-xs sm:text-sm text-gray-500">Form</p>
                <p className="font-semibold text-sm sm:text-base">
                  {report.grade || report.studentGrade || 'N/A'}
                </p>
              </div>
              <div>
                <p className="text-xs sm:text-sm text-gray-500">Generated By</p>
                <p className="font-semibold text-sm sm:text-base truncate">
                  {report.generatedBy || 'System'}
                </p>
              </div>
              <div>
                <p className="text-xs sm:text-sm text-gray-500">Generated On</p>
                <p className="font-semibold text-sm sm:text-base">
                  {report.generatedAt?.toLocaleDateString?.() || new Date().toLocaleDateString()}
                </p>
              </div>
            </div>
          </div>

          {/* Summary Cards */}
          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3 sm:gap-4 mb-6 sm:mb-8">
            <div className="bg-gradient-to-r from-emerald-500 to-emerald-600 rounded-lg p-3 sm:p-4 text-white text-center">
              <div className="text-2xl sm:text-3xl font-bold">
                {(report.overallAverage || 0).toFixed(1)}%
              </div>
              <div className="text-xs sm:text-sm">Overall Average</div>
              <div className="text-lg sm:text-xl mt-2">Grade {report.overallGrade}</div>
            </div>
            <div className="bg-gradient-to-r from-blue-500 to-blue-600 rounded-lg p-3 sm:p-4 text-white text-center">
              <div className="text-2xl sm:text-3xl font-bold">
                {(report.attendanceRate || 0).toFixed(1)}%
              </div>
              <div className="text-xs sm:text-sm">Attendance Rate</div>
            </div>
            <div className="bg-gradient-to-r from-purple-500 to-purple-600 rounded-lg p-3 sm:p-4 text-white text-center">
              <div className="text-2xl sm:text-3xl font-bold">{report.subjects?.length || 0}</div>
              <div className="text-xs sm:text-sm">Subjects</div>
            </div>
          </div>

          {/* Subject Performance */}
          <h3 className="text-lg sm:text-xl font-bold mb-3 sm:mb-4">Subject Performance</h3>
          {report.subjects?.map((subject, idx) => (
            <div key={idx} className="border rounded-lg mb-4 overflow-hidden">
              <div
                className="bg-gray-50 p-3 sm:p-4 flex justify-between items-center cursor-pointer hover:bg-gray-100 gap-2"
                onClick={() => toggleSubject(subject.courseId)}
              >
                <div className="min-w-0 flex-1">
                  <h4 className="font-semibold text-base sm:text-lg truncate">
                    {subject.courseName}
                  </h4>
                  <p className="text-xs sm:text-sm text-gray-500 truncate">
                    Teacher: {subject.teacherName}
                  </p>
                </div>
                <div className="text-right flex-shrink-0">
                  <div className="text-lg sm:text-2xl font-bold text-emerald-600">
                    {(subject.average || 0).toFixed(1)}%
                  </div>
                  <div className="text-xs sm:text-sm text-gray-500">
                    Grade {subject.letterGrade}
                  </div>
                </div>
                {expandedSubject === subject.courseId ? (
                  <ChevronUp className="w-5 h-5 flex-shrink-0" />
                ) : (
                  <ChevronDown className="w-5 h-5 flex-shrink-0" />
                )}
              </div>
              {expandedSubject === subject.courseId && (
                <div className="p-3 sm:p-4 border-t">
                  <h5 className="font-semibold mb-3 text-sm sm:text-base">Assessment Breakdown</h5>
                  <div className="overflow-x-auto -mx-3 sm:-mx-4 px-3 sm:px-4 mb-4">
                    <table className="w-full text-xs sm:text-sm min-w-[500px]">
                      <thead className="bg-gray-100">
                        <tr>
                          <th className="py-2 px-2 sm:px-3 text-left">Type</th>
                          <th className="py-2 px-2 sm:px-3 text-center">Count</th>
                          <th className="py-2 px-2 sm:px-3 text-center">Avg %</th>
                          <th className="py-2 px-2 sm:px-3 text-center">Weight</th>
                          <th className="py-2 px-2 sm:px-3 text-center">Contrib</th>
                        </tr>
                      </thead>
                      <tbody className="divide-y">
                        {subject.assessments && (
                          Array.isArray(subject.assessments)
                            ? subject.assessments.map((a, i) => (
                                <tr key={i}>
                                  <td className="py-2 px-2 sm:px-3 capitalize">{a.type}</td>
                                  <td className="py-2 px-2 sm:px-3 text-center">{a.count}</td>
                                  <td className="py-2 px-2 sm:px-3 text-center">
                                    {(a.average || 0).toFixed(1)}%
                                  </td>
                                  <td className="py-2 px-2 sm:px-3 text-center">
                                    {((a.weight || 0) * 100).toFixed(0)}%
                                  </td>
                                  <td className="py-2 px-2 sm:px-3 text-center">
                                    {((a.average || 0) * (a.weight || 0)).toFixed(1)}%
                                  </td>
                                </tr>
                              ))
                            : Object.entries(subject.assessments).map(([type, data]) => (
                                <tr key={type}>
                                  <td className="py-2 px-2 sm:px-3 capitalize">{type}</td>
                                  <td className="py-2 px-2 sm:px-3 text-center">{data.count || 0}</td>
                                  <td className="py-2 px-2 sm:px-3 text-center">
                                    {(data.average || 0).toFixed(1)}%
                                  </td>
                                  <td className="py-2 px-2 sm:px-3 text-center">
                                    {((data.weight || 0.2) * 100).toFixed(0)}%
                                  </td>
                                  <td className="py-2 px-2 sm:px-3 text-center">
                                    {((data.average || 0) * (data.weight || 0.2)).toFixed(1)}%
                                  </td>
                                </tr>
                              ))
                        )}
                      </tbody>
                    </table>
                  </div>

                  {subject.grades && subject.grades.length > 0 && (
                    <details className="mt-3">
                      <summary className="text-sm text-blue-600 cursor-pointer hover:text-blue-800">
                        View Detailed Grades ({subject.grades.length} assignments)
                      </summary>
                      <div className="mt-2 overflow-x-auto -mx-3 sm:-mx-4 px-3 sm:px-4">
                        <table className="w-full text-xs min-w-[500px]">
                          <thead className="bg-gray-100">
                            <tr>
                              <th className="py-1 px-2 text-left">Assignment</th>
                              <th className="py-1 px-2 text-center">Type</th>
                              <th className="py-1 px-2 text-center">Score</th>
                              <th className="py-1 px-2 text-center">Max</th>
                              <th className="py-1 px-2 text-center">%</th>
                              <th className="py-1 px-2 text-left">Date</th>
                            </tr>
                          </thead>
                          <tbody className="divide-y divide-gray-100">
                            {subject.grades.map((grade, i) => (
                              <tr key={i}>
                                <td className="py-1 px-2">{grade.name}</td>
                                <td className="py-1 px-2 text-center capitalize">{grade.type}</td>
                                <td className="py-1 px-2 text-center">{grade.score}</td>
                                <td className="py-1 px-2 text-center">{grade.maxScore}</td>
                                <td className="py-1 px-2 text-center">
                                  {((grade.score / grade.maxScore) * 100).toFixed(1)}%
                                </td>
                                <td className="py-1 px-2">
                                  {new Date(grade.date).toLocaleDateString()}
                                </td>
                              </tr>
                            ))}
                          </tbody>
                        </table>
                      </div>
                    </details>
                  )}
                </div>
              )}
            </div>
          ))}

          {/* Teacher Comments */}
          <div className="mb-8">
            <h3 className="text-lg sm:text-xl font-bold mb-2">Teacher's Comments</h3>
            <div className="bg-gray-50 p-3 sm:p-4 rounded-lg">
              <p className="text-sm sm:text-base text-gray-700">
                {report.teacherComments || 'No comments provided.'}
              </p>
            </div>
          </div>

          {/* Audit Trail (Admin Only) */}
          {showAuditTrail && report.auditTrail && (
            <div className="mb-8 border-t pt-4">
              <h3 className="text-lg sm:text-xl font-bold mb-2">Audit Trail</h3>
              <div className="bg-gray-50 p-3 sm:p-4 rounded-lg space-y-2">
                {report.auditTrail.map((entry, idx) => (
                  <div
                    key={idx}
                    className="flex items-start gap-2 text-xs sm:text-sm border-b border-gray-200 pb-2"
                  >
                    <div className="w-2 h-2 bg-emerald-500 rounded-full mt-1.5 flex-shrink-0"></div>
                    <div className="min-w-0">
                      <span className="font-medium">{entry.action}</span> by{' '}
                      <span className="font-medium">{entry.userName}</span>
                      <span className="text-gray-500 ml-2">
                        {new Date(entry.timestamp).toLocaleString()}
                      </span>
                      {entry.details && (
                        <p className="text-gray-500 text-xs mt-1">{entry.details}</p>
                      )}
                    </div>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};

export default ReportViewer;